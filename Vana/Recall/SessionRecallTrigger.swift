import Foundation

/// 这一轮该不该把召回工具挂出去。
///
/// 召回**不是一个一直摆在模型眼前的能力**,它是「用户提起了过去」这件事的触发结果——形状上
/// 更接近记忆:什么时候动记忆由 app 说了算(快照在会话开始时读、抽取在会话结束时跑),模型
/// 只管用。召回同理:**触发权归 app,取回权留给模型**。
///
/// 为什么不能只靠工具描述写窄:描述只是建议,而模型每一轮都要重新判断一次「这个问题算不算
/// 接着一段历史」。健康对话句句连着上一句,这个判断天然偏向"算",于是用户问一句今天的步数,
/// 先等一轮检索、再等一轮读回三个月前的对话——那几段旧数字进了上下文,这一轮回答就是带着
/// 污染做的。**工具不挂出去,这个判断就不存在了**,和记忆关掉时不挂 `remember` 同一个道理。
///
/// 反过来也别把它做成「命中就自动把旧对话塞进上下文」。记忆能直接进 system 段,是因为它按
/// 设计只有几十条不会过期的短句;一次旧会话是成篇的、当时的数字。关键词命中只说明"他可能在
/// 说过去",说不出"是哪一次"——中间那道判断必须留给模型,这也正是 `search` / `read` 分两步的
/// 理由。
///
/// 漏判是可以接受的那一边:成本不对称。多翻一次是用户当场多等两个往返、还吃一段过期数据;
/// 漏一次他补一句「上次不是说…」就回来了,而那句话本身又会把工具挂上。
enum SessionRecallTrigger {

    /// 这条会话往后都能召回了吗。
    ///
    /// **粘住不撤**:一条会话里出现过一次「上次」,后面几轮多半还在同一件事上,而工具集
    /// 一轮挂一轮撤会把 prompt 缓存的前缀反复打掉(工具定义排在消息前面,变一次就整份重算)。
    /// 一条会话最多翻一次开关,代价就封顶了。
    static func unlocksRecall(in messages: [ChatMessage]) -> Bool {
        messages.contains { $0.role == .user && mentionsPast($0.text) }
    }

    /// 这句话里,用户在提过去的对话吗。
    ///
    /// 认的是**对话指涉**,不是时间词。「上周步数怎么样」是问数据,现查就有;「上次你说的那个
    /// 方法」才是在指一次聊过的对话。所以词表里是「上次说」「我们聊」「你还记得」这类,不是
    /// 「上周」「前几天」——后者会让一半的健康问题都把工具挂出去,等于没做。
    ///
    /// 宁可宽一点:挂出去只是给了模型一个选项,工具描述那一层还会再挡一次;挂不出去则是这一轮
    /// 彻底没有这个能力。两层的严格程度不一样是有意的。
    static func mentionsPast(_ text: String) -> Bool {
        let lowered = text.lowercased()
        return phrases.contains { lowered.contains($0) }
    }

    /// 词表按「这句话在指一次聊过的对话」挑的。
    ///
    /// 「之前」「以前」单独留着是权衡后的结果:它确实会被「之前几天的数据」蹭到,但那类问题
    /// 只是白挂一次工具(模型照样会去查健康数据),而漏掉「之前你说的那个」是真的答不上来。
    private static let phrases: [String] = [
        "上次", "上回", "上一次", "那次", "上个月我们", "之前", "以前", "早先",
        "说过", "提过", "提到过", "聊过", "讨论过", "分析过", "问过",
        "我们聊", "我们说", "我们讨论", "我们分析", "你说的", "你提的",
        "还记得", "记不记得", "记得吗",
        "last time", "earlier", "we talked", "we discussed", "you said", "you mentioned", "remember"
    ]
}
